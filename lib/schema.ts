import React from "react";

// Shared JSON-LD helpers. Schema is generated from the same data a page renders,
// so structured data cannot drift from visible content.

export const ORG_ID = "https://myesatherapist.com/#organization";

/** Plain text of a React node (strings, numbers, elements, arrays). */
export function nodeToText(node: React.ReactNode): string {
  if (node === null || node === undefined || typeof node === "boolean") return "";
  if (typeof node === "string" || typeof node === "number") return String(node);
  if (Array.isArray(node)) return node.map(nodeToText).join(" ");
  if (React.isValidElement(node)) {
    const el = node as React.ReactElement<{ children?: React.ReactNode }>;
    const tag = typeof el.type === "string" ? el.type : "";
    const text = nodeToText(el.props.children);
    // Keep list items and paragraphs readable as separate sentences.
    return ["li", "p", "div", "br"].includes(tag) ? ` ${text} ` : text;
  }
  return "";
}

const clean = (s: string) => s.replace(/\s+/g, " ").trim();

export function faqPageSchema(items: Array<{ q: React.ReactNode; a: React.ReactNode }>) {
  const mainEntity = items
    .map((item) => ({ name: clean(nodeToText(item.q)), text: clean(nodeToText(item.a)) }))
    .filter((x) => x.name && x.text)
    .map((x) => ({
      "@type": "Question",
      name: x.name,
      acceptedAnswer: { "@type": "Answer", text: x.text },
    }));
  return { "@context": "https://schema.org", "@type": "FAQPage", mainEntity };
}

type Opts = { faq?: boolean };

// Node types never emitted by page schema:
// - FAQPage: generated by the FAQ components from what is displayed.
// - MedicalClinic: misdescribes a platform connecting people to independent clinicians.
// - HowTo / HowToStep: rich result retired by Google.
const DROP_TYPES = new Set(["MedicalClinic", "HowTo", "HowToStep"]);

function types(node: Record<string, unknown>): string[] {
  const t = node["@type"];
  return Array.isArray(t) ? (t as string[]) : t ? [t as string] : [];
}

function shouldDrop(node: unknown, opts: Opts): boolean {
  if (!node || typeof node !== "object" || Array.isArray(node)) return false;
  const ts = types(node as Record<string, unknown>);
  if (ts.some((t) => DROP_TYPES.has(t))) return true;
  if (!opts.faq && ts.includes("FAQPage")) return true;
  return false;
}

function isDroppedRef(value: unknown): boolean {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const v = value as Record<string, unknown>;
  const id = typeof v["@id"] === "string" ? (v["@id"] as string) : "";
  return Object.keys(v).length === 1 && (/#medicalprovider$/.test(id) || /#howto$/.test(id) || /#faq$/.test(id));
}

function walk(value: unknown, opts: Opts): unknown {
  if (Array.isArray(value)) {
    return value.filter((v) => !shouldDrop(v, opts) && !isDroppedRef(v)).map((v) => walk(v, opts));
  }
  if (value && typeof value === "object") {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      // The site has no search, so no SearchAction / sitelinks search box.
      if (k === "potentialAction") {
        const acts = (Array.isArray(v) ? v : [v]).filter(
          (a) => !(a && typeof a === "object" && types(a as Record<string, unknown>).includes("SearchAction")),
        );
        if (acts.length) out[k] = walk(Array.isArray(v) ? acts : acts[0], opts);
        continue;
      }
      if (shouldDrop(v, opts) || isDroppedRef(v)) continue;
      out[k] = walk(v, opts);
    }
    // One Organization entity: give the brand node the shared @id.
    const ts = types(out);
    if (ts.includes("Organization") && !out["@id"] && out.name === "My ESA Therapist") out["@id"] = ORG_ID;
    return out;
  }
  return value;
}

export function sanitizeSchema(schema: unknown, opts: Opts = {}): unknown {
  // A whole block that is itself a dropped type (e.g. a stand-alone FAQPage)
  // becomes an empty object, which search engines ignore.
  if (shouldDrop(schema, opts)) return {};
  return walk(schema, opts);
}

/**
 * Remove nodes from a page's schema by @type, @id or Person name, plus any
 * {"@id": ...} references that pointed at them.
 */
export function pruneSchema(
  schema: unknown,
  rules: { types?: string[]; ids?: string[]; personNames?: string[] },
): unknown {
  const dropIds = new Set<string>(rules.ids || []);
  const matches = (n: Record<string, unknown>) => {
    const ts = types(n);
    if (rules.types && ts.some((t) => rules.types!.includes(t))) return true;
    if (typeof n["@id"] === "string" && dropIds.has(n["@id"] as string)) return true;
    if (rules.personNames && ts.includes("Person") && rules.personNames.includes(String(n.name))) return true;
    return false;
  };
  // First pass: collect ids of matching nodes.
  const collect = (v: unknown) => {
    if (Array.isArray(v)) v.forEach(collect);
    else if (v && typeof v === "object") {
      const n = v as Record<string, unknown>;
      if (n["@type"] && matches(n) && typeof n["@id"] === "string") dropIds.add(n["@id"] as string);
      Object.values(n).forEach(collect);
    }
  };
  collect(schema);
  const isRef = (v: unknown) =>
    !!v && typeof v === "object" && !Array.isArray(v) && Object.keys(v as object).length === 1 &&
    dropIds.has((v as Record<string, unknown>)["@id"] as string);
  const prune = (v: unknown): unknown => {
    if (Array.isArray(v)) {
      return v
        .filter((x) => !(x && typeof x === "object" && !Array.isArray(x) && (x as Record<string, unknown>)["@type"] && matches(x as Record<string, unknown>)) && !isRef(x))
        .map(prune);
    }
    if (v && typeof v === "object") {
      const out: Record<string, unknown> = {};
      for (const [k, x] of Object.entries(v as Record<string, unknown>)) {
        if (isRef(x)) continue;
        if (x && typeof x === "object" && !Array.isArray(x) && (x as Record<string, unknown>)["@type"] && matches(x as Record<string, unknown>)) continue;
        out[k] = prune(x);
      }
      return out;
    }
    return v;
  };
  return prune(schema);
}
